#!/usr/bin/env node
/* tools/vendor.mjs — download the pinned libraries into /vendor and compute SRI hashes.
   Usage (from the project root):   node tools/vendor.mjs
   Output:  vendor/*.js   and   script/libs.vendored.js   (loaded before eg-core.js)
   Needs Node 18+ (built-in fetch).  No npm install. */
import { createHash } from 'node:crypto';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';

const root = process.argv[2] || process.cwd();

export async function loadConfig() {
  const src = await readFile(path.join(root, 'script/libs.config.js'), 'utf8');
  const sandbox = { window: {} }; vm.runInNewContext(src, sandbox);
  return sandbox.window.EG_LIBS;
}
export const sri = (buf) => 'sha384-' + createHash('sha384').update(buf).digest('base64');

export async function vendorAll(fetchFn = fetch) {
  const libs = await loadConfig();
  await mkdir(path.join(root, 'vendor'), { recursive: true });
  const out = {};
  for (const [name, cfg] of Object.entries(libs)) {
    if (name === 'youtube') { console.log('skip  youtube  (cannot be vendored — loaded live from Google on demand)'); continue; }
    const res = await fetchFn(cfg.cdn);
    if (!res.ok) { console.error('FAIL  ' + name + '  HTTP ' + res.status); continue; }
    const buf = Buffer.from(await res.arrayBuffer());
    const file = name + '.js';
    await writeFile(path.join(root, 'vendor', file), buf);
    out[name] = { src: 'vendor/' + file, integrity: sri(buf) };
    console.log('ok    ' + name.padEnd(13) + (buf.length / 1024).toFixed(0).padStart(5) + ' KB  ' + out[name].integrity.slice(0, 22) + '…');
  }
  await writeFile(path.join(root, 'script/libs.vendored.js'),
    '/* GENERATED by tools/vendor.mjs — do not edit */\nwindow.EG_VENDORED = ' + JSON.stringify(out, null, 2) + ';\n');
  return out;
}

if (import.meta.url === 'file://' + process.argv[1]) {
  vendorAll().then(() => console.log('\nDone. Commit vendor/ and script/libs.vendored.js, then add vendor/*.js to sw.js SHELL (optional).'));
}
